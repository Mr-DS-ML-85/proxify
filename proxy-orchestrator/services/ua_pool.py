# Weights: desktop Chrome gets highest probability since it's most common
_WEIGHTS = []
for ua in _USER_AGENTS:
    if "Chrome/" in ua and "Mobile" not in ua and "Edg" not in ua and "OPR" not in ua:
        _WEIGHTS.append(3.0)  # Desktop Chrome is most common
    elif "Firefox/" in ua:
        _WEIGHTS.append(2.0)
    elif "Safari/" in ua and "Chrome" not in ua:
        _WEIGHTS.append(1.5)
    elif "Edg/" in ua:
        _WEIGHTS.append(1.5)
    else:
        _WEIGHTS.append(1.0)


class UserAgentPool:
    """Thread-safe User-Agent pool with weighted random selection and session stickiness."""

    def __init__(self) -> None:
        self._agents = list(_USER_AGENTS)
        self._weights = list(_WEIGHTS)
        self._session_map: dict[str, str] = {}  # session_id -> UA

    def get_random(self) -> str:
        """Get a weighted random User-Agent."""
        return random.choices(self._agents, weights=self._weights, k=1)[0]

    def get_for_session(self, session_id: str) -> str:
        """Get a consistent User-Agent for a session. Same session_id always returns the same UA."""
        if session_id not in self._session_map:
            self._session_map[session_id] = self.get_random()
        return self._session_map[session_id]

    def get_legacy_ua(self) -> str:
        """Get a legacy User-Agent (IE 11) to force 'Lite' non-JS HTML from sites like Google."""
        return "Mozilla/5.0 (Windows NT 10.0; WOW64; Trident/7.0; rv:11.0) like Gecko"

    def release_session(self, session_id: str) -> None:
        """Release a session's User-Agent assignment."""
        self._session_map.pop(session_id, None)

    @property
    def pool_size(self) -> int:
        return len(self._agents)

    @property
    def active_sessions(self) -> int:
        return len(self._session_map)


# Global singleton
ua_pool = UserAgentPool()
